// E2E: cadastro → logout → esqueci a senha → link do e-mail (outbox) → nova senha → login.
import { chromium } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
const db = new PrismaClient();
const base = "http://localhost:3000";
const email = `qa.${Date.now()}@exemplo.com`;
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const p = await (await b.newContext()).newPage();
await p.goto(`${base}/register`, { waitUntil: "networkidle" });
await p.fill('input[name=name]', "Teste QA"); await p.fill('input[name=email]', email); await p.fill('input[name=password]', "Senha1234");
await p.getByRole("checkbox").click(); await p.click('button[type=submit]');
await p.waitForURL(/dashboard/); console.log("1. cadastro →", p.url().replace(base, ""));
await p.getByRole("button", { name: "Menu da conta" }).click(); await p.getByRole("menuitem", { name: "Sair" }).click();
await p.waitForURL(/login/); console.log("2. logout →", p.url().replace(base, ""));
await p.goto(`${base}/forgot-password`, { waitUntil: "networkidle" });
await p.fill('input[name=email]', email); await p.click('button[type=submit]');
await p.getByText("Verifique seu e-mail").waitFor(); console.log("3. pedido de redefinição enviado");
const mail = await db.emailMessage.findFirst({ where: { to: email, template: "password-reset" }, orderBy: { createdAt: "desc" } });
const link = mail.text.match(/https?:\/\/\S+reset-password\?token=\S+/)[0];
console.log("4. e-mail na caixa de saída:", mail.status, "| link encontrado");
await p.goto(link.replace(/^https?:\/\/[^/]+/, base), { waitUntil: "networkidle" });
await p.fill('input[name=password]', "NovaSenha99"); await p.fill('input[name=confirm]', "NovaSenha99"); await p.click('button[type=submit]');
await p.waitForURL(/login\?reset=1/); console.log("5. senha redefinida →", p.url().replace(base, ""));
await p.goto(link.replace(/^https?:\/\/[^/]+/, base), { waitUntil: "networkidle" });
await p.fill('input[name=password]', "OutraSenha1"); await p.fill('input[name=confirm]', "OutraSenha1"); await p.click('button[type=submit]');
await p.getByText(/inválido ou expirou/).waitFor(); console.log("6. link reutilizado é rejeitado ✓");
await p.goto(`${base}/login`, { waitUntil: "networkidle" });
await p.fill('input[name=email]', email); await p.fill('input[name=password]', "Senha1234"); await p.click('button[type=submit]');
await p.getByText("E-mail ou senha incorretos.").waitFor(); console.log("7. senha antiga rejeitada ✓");
await p.fill('input[name=password]', "NovaSenha99"); await p.click('button[type=submit]');
await p.waitForURL(/dashboard/); console.log("8. login com a nova senha ✓");
await db.user.delete({ where: { email } }); await db.emailMessage.deleteMany({ where: { to: email } });
await db.$disconnect(); await b.close();
